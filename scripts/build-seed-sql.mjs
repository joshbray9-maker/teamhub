// Builds seed/seed.sql from the TeamHub artifact export in seed/export/.
//   ADMIN_EMAIL=you@example.com npm run seed:sql
// Then paste seed/seed.sql into the Supabase SQL editor and run it. It is safe to re-run:
// it replaces the seeded teams (matched by legacy_id) and everything under them.
// ADMIN_EMAIL becomes admin of every seeded organization (now if that account exists,
// otherwise as soon as it signs up).
//
// The export holds schedules, S&C day themes and league tables only. Coach notes/to-dos
// were deliberately not exported (free text that could mention athletes); copy them by hand.

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'seed', 'export');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const opt = (p, d) => (existsSync(join(root, p)) ? read(p) : d);
const warn = (m) => process.stderr.write(`warning: ${m}\n`);

const adminEmail = (process.env.ADMIN_EMAIL || '').trim().toLowerCase();
if (!adminEmail) { process.stderr.write('Set ADMIN_EMAIL, e.g. ADMIN_EMAIL=you@example.com npm run seed:sql\n'); process.exit(1); }

// Teams with no organization in the artifact get one named after the school.
const ORG_FOR_UNSET = { t_rugby: "Bishop's University" };
const slugify = (s) => s.replace(/['’]/g, '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const qn = (v) => (v === null || v === undefined || v === '' || isNaN(+v) ? 'null' : String(+v));
const qj = (v) => `${q(JSON.stringify(v))}::jsonb`;
const isDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s || '');
const isMonday = (s) => new Date(s + 'T12:00:00Z').getUTCDay() === 1;
const teamRef = (legacy) => `(select id from public.teams where legacy_id = ${q(legacy)})`;

const order = opt('config/app.json', {}).teamOrder || [];
const teams = readdirSync(join(root, 'teams')).filter((f) => f.endsWith('.json')).map((f) => ({ legacy: f.replace(/\.json$/, ''), ...read(`teams/${f}`) }));
teams.sort((a, b) => ((order.indexOf(a.legacy) + 1 || 999) - (order.indexOf(b.legacy) + 1 || 999)) || (a.created || 0) - (b.created || 0));

const orgs = new Map();
for (const t of teams) { t.orgName = t.org || ORG_FOR_UNSET[t.legacy] || t.school || t.name; orgs.set(t.orgName, slugify(t.orgName)); }

const out = [];
const emit = (s) => out.push(s);
emit('-- Generated by scripts/build-seed-sql.mjs from the TeamHub artifact export. Re-runnable.');
emit('begin;');
for (const [name, slug] of orgs) emit(`insert into public.organizations (name, slug) values (${q(name)}, ${q(slug)}) on conflict (slug) do nothing;`);
for (const [, slug] of orgs) {
  const org = `(select id from public.organizations where slug = ${q(slug)})`;
  emit(`insert into public.memberships (org_id, user_id, role) select ${org}, p.id, 'admin' from public.profiles p where p.email = ${q(adminEmail)} on conflict (org_id, user_id) do update set role = 'admin';`);
  emit(`insert into public.invites (org_id, email, role) select ${org}, ${q(adminEmail)}, 'admin' where not exists (select 1 from public.profiles where email = ${q(adminEmail)}) on conflict (org_id, email) do update set role = 'admin';`);
}
emit(`delete from public.teams where legacy_id in (${teams.map((t) => q(t.legacy)).join(', ')});`);

let counts = { games: 0, events: 0, notifs: 0, scDays: 0, scWeeks: 0 };
teams.forEach((t, i) => {
  const tr = teamRef(t.legacy);
  const logo = t.logo && /^https?:/.test(t.logo) ? t.logo : null;
  if (t.logo && !logo) warn(`${t.name}: logo was stored inside the artifact; re-upload it in Team settings`);
  emit(`\n-- ${t.name}`);
  emit(`insert into public.teams (org_id, legacy_id, name, school, sport, level, color, logo_url, league_name, league_url, sort_order) values ((select id from public.organizations where slug = ${q(orgs.get(t.orgName))}), ${q(t.legacy)}, ${q(t.name)}, ${q(t.school || '')}, ${q(t.sport || 'hockey')}, ${q(t.level || 'high-school')}, ${q(t.color || '#1f5fbf')}, ${q(logo)}, ${q(t.leagueName || '')}, ${q(t.leagueUrl || '')}, ${i});`);

  const d = (k, def) => opt(`teams/${t.legacy}/data/${k}.json`, def);
  const league = d('league', { groups: [], games: [] });
  const games = (league.games || []).filter((g) => { if (!isDate(g.date) || !g.home || !g.away) { warn(`${t.name}: skipped game without date/teams`); return false; } return true; });
  if (games.length) {
    emit(`insert into public.games (team_id, date, time, home, away, home_score, away_score, venue, round, source) values`);
    emit(games.map((g) => `  (${tr}, ${q(g.date)}, ${q(g.time || '')}, ${q(g.home)}, ${q(g.away)}, ${qn(g.hs)}, ${qn(g.as)}, ${q(g.venue || '')}, ${q(g.round || '')}, ${q(g.source || 'manual')})`).join(',\n') + ';');
    counts.games += games.length;
  }
  if ((league.groups || []).length) emit(`insert into public.standings (team_id, groups, updated_at) values (${tr}, ${qj(league.groups)}, ${league.updatedAt ? `to_timestamp(${league.updatedAt / 1000})` : 'now()'});`);

  const events = (d('events', { items: [] }).items || []).filter((e) => isDate(e.date) && e.title);
  if (events.length) {
    emit(`insert into public.events (team_id, date, time, title, kind, location) values`);
    emit(events.map((e) => `  (${tr}, ${q(e.date)}, ${q(e.time || '')}, ${q(e.title)}, ${q(e.kind === 'practice' ? 'practice' : 'event')}, ${q(e.location || '')})`).join(',\n') + ';');
    counts.events += events.length;
  }

  const notifs = d('notifs', { items: [] }).items || [];
  if (notifs.length) {
    emit(`insert into public.notifications (team_id, text, read, created_at) values`);
    emit(notifs.map((n) => `  (${tr}, ${q(n.text)}, ${n.read ? 'true' : 'false'}, ${n.ts ? `to_timestamp(${n.ts / 1000})` : 'now()'})`).join(',\n') + ';');
    counts.notifs += notifs.length;
  }

  const sc = d('sc', { weeks: {}, days: {} });
  const weeks = Object.entries(sc.weeks || {}).filter(([k]) => { if (!isDate(k) || !isMonday(k)) { warn(`${t.name}: S&C week ${k} is not a Monday, skipped`); return false; } return true; });
  if (weeks.length) {
    emit(`insert into public.sc_weeks (team_id, week_start, phase, season_week) values`);
    emit(weeks.map(([k, w]) => `  (${tr}, ${q(k)}, ${q(w.phase || '')}, ${q(w.week || '')})`).join(',\n') + ';');
    counts.scWeeks += weeks.length;
  }
  const INT = new Set(['', 'off', 'light', 'moderate', 'heavy', 'game']);
  const days = Object.entries(sc.days || {}).filter(([k]) => isDate(k));
  if (days.length) {
    emit(`insert into public.sc_days (team_id, date, theme, intensity, note, pdf_color) values`);
    emit(days.map(([k, x]) => `  (${tr}, ${q(k)}, ${q(x.theme || '')}, ${q(INT.has(x.intensity || '') ? x.intensity || '' : '')}, ${q(x.note || '')}, ${q(x.pdfColor || null)})`).join(',\n') + ';');
    counts.scDays += days.length;
  }
  if (sc.loads) emit(`insert into public.settings (team_id, key, value) values (${tr}, 'sc_loads', ${qj(sc.loads)});`);
  if (sc.band) emit(`insert into public.settings (team_id, key, value) values (${tr}, 'sc_band', ${qj(sc.band)});`);
});
emit('\ncommit;');
process.stdout.write(out.join('\n') + '\n');
process.stderr.write(`seed.sql: ${orgs.size} organizations, ${teams.length} teams, ${counts.games} games, ${counts.events} events, ${counts.notifs} notifications, ${counts.scWeeks} S&C weeks, ${counts.scDays} S&C days\n`);
